using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using SenX.Monitor.Magnetar.Patching;
using Torch.Managers.PatchManager;
using Torch.Managers.PatchManager.MSIL;

namespace SenX.Monitor.Torch.Lock;

/// <summary>
/// Writes the Torch build's fingerprints, read with Torch's own IL reader from the game DLLs Torch runs.
/// While it's there it rewrites every caller in memory and counts the sites that really changed, which
/// finds a table entry that matches but won't fit. Nothing is emitted, patched or run.
///
/// Usage: SenX.Monitor.Torch.Lock TorchFolder [--write-lock file]
/// </summary>
internal static class Program
{
    private static string[] s_folders = Array.Empty<string>();

    private static int Main(string[] args)
    {
        if (args.Length < 1)
        {
            Console.WriteLine("Usage: SenX.Monitor.Torch.Lock TorchFolder [--write-lock file]");
            return 2;
        }

        s_folders = new[] { args[0], Path.Combine(args[0], "DedicatedServer64") };
        AppDomain.CurrentDomain.AssemblyResolve += Resolve;

        int option = Array.IndexOf(args, "--write-lock");
        return Run(option >= 0 && option + 1 < args.Length ? args[option + 1] : null);
    }

    // Everything game-side has to wait for the resolver, so it stays out of Main.
    [MethodImpl(MethodImplOptions.NoInlining)]
    private static int Run(string? lockFile)
    {
        List<CallerSpec> table = TargetTable.Build();
        List<SiteResult> sites = PatchEngine.Evaluate(table);
        int problems = 0;

        foreach (CallerSpec caller in table)
        {
            if (caller.Method == null)
            {
                Console.WriteLine("Missing method: " + caller.Id);
                problems++;
                continue;
            }

            ShowLostLeaves(caller);

            if (TorchIl.HasSiblingCatches(caller.Method))
            {
                Console.WriteLine("Several catches on one try, which Torch rebuilds nested: " + caller.Id);
                problems++;
            }

            Dictionary<CallTarget, int> rewritten = DryRewrite(caller, out List<MsilInstruction> output);

            if (TorchIl.LostLeaves(output).Count > 0)
            {
                Console.WriteLine("A rewrite still loses a leave: " + caller.Id);
                problems++;
            }

            foreach (CallTarget target in caller.Targets)
            {
                rewritten.TryGetValue(target, out int done);

                if (done != target.Expected)
                {
                    Console.WriteLine("Would rewrite " + done + " of " + target.Expected + ": " + caller.Id + " -> " + target.Name);
                    problems++;
                }
            }
        }

        foreach (IGrouping<SiteState, SiteResult> group in sites.GroupBy(site => site.State))
            Console.WriteLine(group.Key + ": " + group.Count());

        Console.WriteLine("Callers " + table.Count + ", sites " + sites.Count + ", problems " + problems + ".");

        if (lockFile != null)
            WriteLock(table, lockFile);

        return problems == 0 ? 0 : 1;
    }

    // A leave a plain rebuild would drop, which the rewrite is about to keep, and the code around it.
    private static void ShowLostLeaves(CallerSpec caller)
    {
        List<MsilInstruction> code = PatchUtilities.ReadInstructions(caller.Method!).ToList();

        foreach (int at in TorchIl.LostLeaves(code))
        {
            var branch = (MsilOperandBrTarget)code[at].Operand;
            int target = code.FindIndex(instruction => instruction.Labels.Contains(branch.Target));

            Console.WriteLine("Leave at IL_" + code[at].Offset.ToString("X4") + " goes to IL_" + code[target].Offset.ToString("X4") + " in " + caller.Id);

            for (int i = Math.Max(0, at - 2); i < Math.Min(code.Count, at + 6); i++)
                Console.WriteLine("    IL_" + code[i].Offset.ToString("X4") + " " + code[i].OpCode + " " + string.Join(",", code[i].TryCatchOperations.Select(operation => operation.Type)));
        }
    }

    private static Dictionary<CallTarget, int> DryRewrite(CallerSpec caller, out List<MsilInstruction> output)
    {
        var rewritten = new Dictionary<CallTarget, int>();
        int nextLocal = 1000;

        output = MsilRewriter.Rewrite(PatchUtilities.ReadInstructions(caller.Method!), caller.Targets, _ => new MsilLocal(nextLocal++), rewritten);
        return rewritten;
    }

    private static void WriteLock(IEnumerable<CallerSpec> table, string file)
    {
        var text = new StringBuilder();
        text.AppendLine("// Generated by tools/SenX.Monitor.Torch.Lock. Do not edit by hand.");
        text.AppendLine("using System;");
        text.AppendLine("using System.Collections.Generic;");
        text.AppendLine();
        text.AppendLine("namespace SenX.Monitor.Magnetar.Patching;");
        text.AppendLine();
        text.AppendLine("internal static class Fingerprints");
        text.AppendLine("{");
        text.AppendLine("    public static readonly Dictionary<string, string> Known = new(StringComparer.Ordinal)");
        text.AppendLine("    {");

        foreach (CallerSpec caller in table.Where(caller => caller.Method != null).OrderBy(caller => caller.Id, StringComparer.Ordinal))
            text.AppendLine("        [\"" + caller.Id + "\"] = \"" + IlFingerprint.Compute(caller.Method!) + "\",");

        text.AppendLine("    };");
        text.AppendLine("}");

        File.WriteAllText(file, text.ToString());
        Console.WriteLine("Wrote " + file);
    }

    private static Assembly? Resolve(object sender, ResolveEventArgs args)
    {
        string name = new AssemblyName(args.Name).Name;

        foreach (string folder in s_folders)
        {
            foreach (string extension in new[] { ".dll", ".exe" })
            {
                string path = Path.Combine(folder, name + extension);

                if (File.Exists(path))
                    return Assembly.LoadFrom(path);
            }
        }

        return null;
    }
}
